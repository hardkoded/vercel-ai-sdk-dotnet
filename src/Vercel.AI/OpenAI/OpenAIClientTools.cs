using System.Text.Json;
using System.Text.Json.Serialization;
using Vercel.AI.GenerateText;

namespace Vercel.AI.OpenAI;

/// <summary>The shell action of a <see cref="OpenAIShellInput"/>. Maps to the <c>action</c> of the upstream shell input.</summary>
public sealed class OpenAIShellAction
{
    /// <summary>A list of shell commands to execute.</summary>
    public IReadOnlyList<string> Commands { get; set; } = [];

    /// <summary>Optional timeout in milliseconds for the commands.</summary>
    public double? TimeoutMs { get; set; }

    /// <summary>Optional maximum number of characters to return from each command.</summary>
    public double? MaxOutputLength { get; set; }
}

/// <summary>The input the model sends to the shell tool.</summary>
public sealed class OpenAIShellInput
{
    /// <summary>Shell tool action containing commands to execute.</summary>
    public OpenAIShellAction Action { get; set; } = new();
}

/// <summary>The outcome of one shell command: <c>timeout</c>, or <c>exit</c> with <see cref="ExitCode"/>.</summary>
public sealed class OpenAIShellOutcome
{
    /// <summary><c>timeout</c> or <c>exit</c>.</summary>
    public string Type { get; set; } = "exit";

    /// <summary>Exit code of an <c>exit</c> outcome.</summary>
    public double? ExitCode { get; set; }
}

/// <summary>The output of one shell command.</summary>
public sealed class OpenAIShellOutputItem
{
    /// <summary>Standard output from the command.</summary>
    public string Stdout { get; set; } = "";

    /// <summary>Standard error from the command.</summary>
    public string Stderr { get; set; } = "";

    /// <summary>The outcome of the shell execution.</summary>
    public OpenAIShellOutcome Outcome { get; set; } = new();
}

/// <summary>The output of the shell tool, what the application sends back.</summary>
public sealed class OpenAIShellOutput
{
    /// <summary>Optional maximum number of characters that was applied to each command's output.</summary>
    public double? MaxOutputLength { get; set; }

    /// <summary>An array of shell call output contents.</summary>
    public IReadOnlyList<OpenAIShellOutputItem> Output { get; set; } = [];
}

/// <summary>A patch operation of the apply_patch tool: <c>create_file</c>, <c>delete_file</c>, or <c>update_file</c>.</summary>
public sealed class OpenAIApplyPatchOperation
{
    /// <summary><c>create_file</c>, <c>delete_file</c>, or <c>update_file</c>.</summary>
    public string Type { get; set; } = "";

    /// <summary>Path of the file relative to the workspace root.</summary>
    public string Path { get; set; } = "";

    /// <summary>Unified diff content of a <c>create_file</c> or <c>update_file</c> operation.</summary>
    public string? Diff { get; set; }
}

/// <summary>The input the model sends to the apply_patch tool.</summary>
public sealed class OpenAIApplyPatchInput
{
    /// <summary>The unique ID of the apply patch tool call generated by the model.</summary>
    public string CallId { get; set; } = "";

    /// <summary>The create, delete, or update instruction for the apply_patch tool call.</summary>
    public OpenAIApplyPatchOperation Operation { get; set; } = new();
}

/// <summary>The output of the apply_patch tool, what the application sends back.</summary>
public sealed class OpenAIApplyPatchOutput
{
    /// <summary><c>completed</c> when the patch was applied, <c>failed</c> when it was not.</summary>
    public string Status { get; set; } = "completed";

    /// <summary>Optional human-readable log text, such as patch results or errors.</summary>
    public string? Output { get; set; }
}

internal static class OpenAIClientTools
{
    internal static readonly JsonSerializerOptions Json = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        PropertyNameCaseInsensitive = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
    };

    internal const string ShellInputSchema =
        "{\"type\":\"object\",\"properties\":{\"action\":{\"type\":\"object\",\"properties\":{\"commands\":{\"type\":\"array\",\"items\":{\"type\":\"string\"}},\"timeoutMs\":{\"type\":\"number\"},\"maxOutputLength\":{\"type\":\"number\"}},\"required\":[\"commands\"]}},\"required\":[\"action\"]}";

    internal const string ApplyPatchInputSchema =
        "{\"type\":\"object\",\"properties\":{\"callId\":{\"type\":\"string\"},\"operation\":{\"type\":\"object\",\"properties\":{\"type\":{\"type\":\"string\",\"enum\":[\"create_file\",\"delete_file\",\"update_file\"]},\"path\":{\"type\":\"string\"},\"diff\":{\"type\":\"string\"}},\"required\":[\"type\",\"path\"]}},\"required\":[\"callId\",\"operation\"]}";

    internal static JsonElement ParseSchema(string schema)
    {
        using var document = JsonDocument.Parse(schema);
        return document.RootElement.Clone();
    }

    // Wires the typed callbacks of a client-executed tool to the JSON-based Tool.
    internal static Tool Build<TInput, TOutput>(
        Tool tool,
        Func<TInput, ToolExecutionOptions, Task<TOutput>>? execute,
        bool needsApproval,
        Func<TInput, ToolNeedsApprovalOptions, Task<bool>>? needsApprovalFunction)
    {
        if (execute != null)
        {
            tool.ExecuteWithOptions = async (input, options) =>
            {
                var output = await execute(Deserialize<TInput>(input), options).ConfigureAwait(false);
                return JsonSerializer.Serialize(output, Json);
            };
        }

        tool.NeedsApproval = needsApproval;
        if (needsApprovalFunction != null)
        {
            tool.NeedsApprovalFunction = (input, options) => needsApprovalFunction(Deserialize<TInput>(input), options);
        }

        return tool;
    }

    private static T Deserialize<T>(JsonElement input) =>
        input.Deserialize<T>(Json) ?? throw new JsonException("The tool input is null.");
}
